"""OpenFedLLM's main_sft.py with fedguard mounted: the smallest complete integration for this host.
Every line that is not upstream's is marked `# [guard]`; the call sites are the ones listed in
fedguard/adapters/OPENFEDLLM.md. Generated by integrations/make_examples.py from external/OpenFedLLM
(commit 14c6af2); `main_sft.guard.patch` next to it is the difference. Edit the generator, not this file.

  --guard_policy FILE          a control policy (fedguard.policy): the controls of both sides, their arguments, whose
                               actions are enforced, and the extension layers they rely on. Replaces the four flags below
  --guard_modules a,b          server-side plugins (names from fedguard.methods.METHODS and fedguard.plugins.BUILTIN)
  --guard_client_modules a,b   client-side plugins; a model handle is built when one of them asks for it
  --guard_record DIR           write records there (server side, and one per client)
  --guard_apply 0|1            let plugins act (default 1); 0 records what they would have done
  --guard_trainer_ext 1        switch on the trainer extension layer for client plugins at CLIENT_LOSS. That is not
                               this host's original behavior: each client trainer's compute_loss gets wrapped

Without plugins the training result is the same as upstream's, bit for bit (integrations/check_bitwise.sh
compares them).
"""
import argparse  # [guard]
import sys  # [guard]
from pathlib import Path  # [guard]

_ROOT = Path(__file__).resolve().parents[2]  # [guard]
sys.path[:0] = [str(_ROOT), str(_ROOT / "integrations")]  # [guard]
from host_shims import apply_shims, split_argv  # noqa: E402  # [guard] the same environment shims the unmodified upstream run gets

_p = argparse.ArgumentParser(add_help=False)  # [guard]
_p.add_argument("--guard_policy", default="")  # [guard]
_p.add_argument("--guard_modules", default="")  # [guard]
_p.add_argument("--guard_client_modules", default="")  # [guard]
_p.add_argument("--guard_record", default="")  # [guard]
_p.add_argument("--guard_apply", type=int, default=1)  # [guard]
_p.add_argument("--guard_trainer_ext", type=int, default=0)  # [guard]
_p.add_argument("--device", default="auto", choices=["auto", "cpu"])  # [guard]
gargs = split_argv(_p)  # [guard]
apply_shims(gargs.device, upstream=_ROOT / "external" / "OpenFedLLM")  # [guard]

import copy
import os
from tqdm import tqdm
import numpy as np

from transformers import AutoModelForCausalLM, AutoTokenizer
from trl import DataCollatorForCompletionOnlyLM
from peft import get_peft_model, get_peft_model_state_dict, set_peft_model_state_dict, prepare_model_for_kbit_training

from utils import *
from federated_learning import *
from config import get_config, save_config, get_model_config, get_training_args

from datasets import Dataset  # noqa: E402  # [guard]
from safetensors.torch import save_file  # noqa: E402  # [guard]
from fedguard.adapters.hf_trainer import GuardStepCallback  # noqa: E402  # [guard]
from fedguard.adapters.hf_trainer_ext import extend_trainer  # noqa: E402  # [guard]
from fedguard.adapters.openfedllm import OpenFedLLMGuard  # noqa: E402  # [guard]
from fedguard.client import ClientGuard  # noqa: E402  # [guard]
from fedguard.core.types import RunSpec  # noqa: E402  # [guard]
from fedguard.policy import Policy  # noqa: E402  # [guard]
from fedguard.recorder.store import Recorder  # noqa: E402  # [guard]
from fedguard.views.client import DataView  # noqa: E402  # [guard]

# ===== Define the arguments =====
script_args, fed_args, peft_config = get_config()
training_args = get_training_args(script_args, script_args.learning_rate)
save_config(script_args, fed_args)
print(script_args, fed_args)

# ===== Load the dataset =====
dataset = get_dataset(script_args.dataset_name, script_args.local_data_dir)
dataset = process_sft_dataset(script_args.dataset_name, dataset, script_args.dataset_sample)

# ===== Split the dataset into clients =====
local_datasets = split_dataset(fed_args, script_args, dataset)
sample_num_list = [len(local_datasets[i]) for i in range(fed_args.num_clients)]

# ===== Mount fedguard =====  # [guard]
policy = Policy.load(gargs.guard_policy) if gargs.guard_policy else Policy.from_names(  # [guard] one policy either way
    server=gargs.guard_modules, client=gargs.guard_client_modules, enforce_server=bool(gargs.guard_apply),
    enforce_client=bool(gargs.guard_apply), fail="closed", extensions={"trainer"} if gargs.guard_trainer_ext else ())
_run_id = os.path.basename(script_args.output_dir.rstrip("/"))  # [guard]
_spec = RunSpec(run_id=_run_id, seed=script_args.seed, num_clients=fed_args.num_clients,  # [guard]
                lora_scale=script_args.peft_lora_alpha / script_args.peft_lora_r)
_rec = Recorder(gargs.guard_record, _run_id) if gargs.guard_record else None  # [guard]
guard = OpenFedLLMGuard(policy.runner("server", _spec, _rec), _rec)  # [guard]
_text = lambda row: " ".join(str(row[k]) for k in sorted(row))  # noqa: E731  # [guard] what a sample is hashed by
client_guards = {}  # [guard]


def client_guard(client):  # [guard] one ClientGuard per client; None when there is nothing for it to do
    if not (policy.client.controls or gargs.guard_record):
        return None
    if client not in client_guards:
        cid = f"client{client}"
        runner = policy.runner("client", _spec)
        client_guards[client] = ClientGuard(cid, runner, Recorder(gargs.guard_record, _run_id, scope=cid) if gargs.guard_record else None)
    return client_guards[client]


# ===== Get model config =====
device_map, quantization_config, torch_dtype = get_model_config(script_args)

model = AutoModelForCausalLM.from_pretrained(
    script_args.model_name_or_path,
    quantization_config=quantization_config,
    device_map=device_map,
    trust_remote_code=script_args.trust_remote_code,
    torch_dtype=torch_dtype,
)

if script_args.load_in_8bit or script_args.load_in_4bit:
    model = prepare_model_for_kbit_training(
                model, use_gradient_checkpointing=training_args.gradient_checkpointing
            )

model = get_peft_model(model, peft_config)
model.print_trainable_parameters()

model.config.use_cache = False  # silence the warnings. Please re-enable for inference!

if training_args.gradient_checkpointing:
    model.enable_input_require_grads()

# ===== Define the global and local models =====
global_dict = copy.deepcopy(get_peft_model_state_dict(model))
local_dict_list = [copy.deepcopy(global_dict) for i in range(fed_args.num_clients)]
proxy_dict, opt_proxy_dict = get_proxy_dict(fed_args, global_dict)
global_auxiliary, auxiliary_model_list, auxiliary_delta_dict = get_auxiliary_dict(fed_args, global_dict)

# ===== Define the tokenizer =====
tokenizer = AutoTokenizer.from_pretrained(script_args.model_name_or_path, use_fast=False, padding_side="right")
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.unk_token   # following vicuna

# ===== Define the formatting function (cater to TRL SFTTrainer)=====
formatting_prompts_func, response_template = get_formatting_prompts_func(script_args.template, tokenizer.eos_token)
response_template_ids = tokenizer.encode(response_template, add_special_tokens=False)[2:]   # Now we have it like in the dataset texts: `[2277, 29937, 4007, 22137, 29901]` for Llama2
data_collator = DataCollatorForCompletionOnlyLM(response_template_ids, tokenizer=tokenizer)

client_handle = None  # [guard] a model handle for client plugins that run the model themselves
if "model_handle" in policy.needs("client"):  # [guard]
    from fedguard.adapters.hf_model import HFModelHandle  # noqa: E402

    def _split(row):  # (prompt, answer) in the training format: the loss is on the answer
        text = formatting_prompts_func({"instruction": [row["instruction"]], "response": [row["response"]]})[0]
        head, sep, tail = text.rpartition(response_template)
        return (head + sep, tail) if sep else ("", text)
    model.to(training_args.device)   # upstream leaves the model on the CPU until the first trainer moves it
    client_handle = HFModelHandle(model, tokenizer, split_of=_split, max_length=script_args.seq_length)

# ===== Start federated training =====
training_loss = [[] for i in range(fed_args.num_clients)]

for round in tqdm(range(fed_args.num_rounds)):

    clients_this_round = get_clients_this_round(fed_args, round)

    print(f">> ==================== Round {round+1} : {clients_this_round} ====================")
    guard.begin_round(round, global_dict, clients_this_round)  # [guard] SERVER_DISTRIBUTE
    round_data = {c: get_dataset_this_round(local_datasets[c], round, fed_args, script_args) for c in clients_this_round}  # [guard] once per round
    exchange = any(client_guard(c) is not None and client_guard(c).wants_exchange for c in clients_this_round)  # [guard]
    reply = ({}, {})  # [guard]
    if exchange:  # [guard] CLIENT_ANNOUNCE for every sampled client, then SERVER_EXCHANGE, before anyone trains
        announced = {}
        for client in clients_this_round:
            cg = client_guard(client)
            received = guard.model_for(client)
            set_peft_model_state_dict(model, received)
            cg.begin_round(round, received, messages=guard.outbox, attachments=guard.outbox_tensors, defer=True)
            announced[client] = cg.announce(DataView(round_data[client], text_of=_text), client_handle)
        reply = guard.exchange(announced)
    
    for client in range(fed_args.num_clients):

        if client not in clients_this_round:
            training_loss[client].append(-1)            # -1 is an indicator of not training
            continue

        received = guard.model_for(client)  # [guard] the round's global LoRA, unless this client was sent its own
        set_peft_model_state_dict(model, received)   # sync the global model to the local model

        sub_dataset = round_data[client]      # get the required sub-dataset for this round
        new_lr = cosine_learning_rate(round, fed_args.num_rounds, script_args.learning_rate, 1e-6)      # manually schedule the learning rate
        training_args = get_training_args(script_args, new_lr)
        cg = client_guard(client)  # [guard]
        if cg is not None:  # [guard] CLIENT_PRE_TRAIN: what arrived, and what it will be trained on
            if exchange:
                cg.deliver(*reply)
                cg.pre_train(model_handle=client_handle)
            else:
                cg.begin_round(round, received, data=DataView(sub_dataset, text_of=_text), model_handle=client_handle,
                               messages=guard.outbox, attachments=guard.outbox_tensors)
            if cg.runner is not None and cg.runner.apply_actions:   # what applied client actions left to train on, and from
                if cg.runner.received() is not None:
                    set_peft_model_state_dict(model, cg.start_state())
                if cg.runner.masked() or any(cg.runner.sample_edits()):
                    sub_dataset = Dataset.from_list([dict(r) for r in cg.training_samples()])
        if len(sub_dataset) == 0:  # [guard] every sample was masked: this client sends the model back unchanged
            training_loss[client].append(-1)
            local_dict_list[client] = copy.deepcopy(get_peft_model_state_dict(model))
            if cg is not None:
                cg.before_upload(local_dict_list[client], {"num_examples": 0.0})
                cg.end_round()
            guard.on_upload(client, local_dict_list[client], {"num_examples": 0.0})
            continue

        # ===== Train local model on the client side =====
        trainer = get_fed_local_sft_trainer(
            model=model,
            tokenizer=tokenizer,
            training_args=training_args,
            local_dataset=sub_dataset,
            formatting_prompts_func=formatting_prompts_func,
            data_collator=data_collator,
            global_dict=global_dict,
            fed_args=fed_args,
            script_args=script_args,
            local_auxiliary=auxiliary_model_list[client],
            global_auxiliary=global_auxiliary,
        )

        if cg is not None and "trainer" in policy.extensions:  # [guard] CLIENT_LOSS: an extension layer, not the host's behavior
            extend_trainer(trainer, cg)
        if cg is not None:  # [guard] CLIENT_PRE_STEP and CLIENT_STEP, through the trainer's callbacks
            trainer.add_callback(GuardStepCallback(cg, lora_state=get_peft_model_state_dict))
        results = trainer.train()
        training_loss[client].append(results.training_loss)

        # ===== Client transmits local information to server =====
        if fed_args.fed_alg == 'scaffold':
            auxiliary_model_list[client], auxiliary_delta_dict[client] = trainer.get_auxiliary_param()

        local_dict_list[client] = copy.deepcopy(get_peft_model_state_dict(model))   # copy is needed!
        _reported = {"num_examples": float(sample_num_list[client]), "train_loss": results.training_loss}  # [guard] what upstream weights by
        _messages, _tensors = {}, {}  # [guard]
        if cg is not None:  # [guard] CLIENT_POST_TRAIN: the local result, before it leaves the client
            cg.before_upload(local_dict_list[client], _reported)
            _messages, _tensors = cg.outbox(), cg.outbox_tensors()
            if cg.runner is not None and cg.client_id in cg.runner.transformed():   # an applied transform_update
                local_dict_list[client] = {k: v.to(local_dict_list[client][k].device, local_dict_list[client][k].dtype)
                                           for k, v in cg.upload_state().items()}
            cg.end_round()
        guard.on_upload(client, local_dict_list[client], _reported, messages=_messages, attachments=_tensors)  # [guard]

    # ===== Server aggregates the local models =====
    kept, weights = guard.before_aggregate(clients_this_round, sample_num_list)  # [guard] SERVER_RECEIVE, SERVER_AGGREGATE
    for _c, _lora in guard.transformed.items():  # [guard] updates an applied transform_update replaced
        local_dict_list[_c] = {k: _lora[k].to(v.device, v.dtype) for k, v in local_dict_list[_c].items()}
    if kept:  # [guard] if every update is excluded, the previous global model stays
        global_dict, global_auxiliary = global_aggregate(
            fed_args, global_dict, local_dict_list, weights, \
            kept, round, proxy_dict=proxy_dict, \
            opt_proxy_dict=opt_proxy_dict, auxiliary_info=(global_auxiliary, auxiliary_delta_dict)
        )
        global_dict = guard.after_aggregate(global_dict)  # [guard] SERVER_POST_AGGREGATE
    guard.end_round({"sampled": clients_this_round, "aggregated": kept})  # [guard]
    set_peft_model_state_dict(model, global_dict)   # Update global model

    # ===== Save the model =====
    if (round+1) % fed_args.save_model_freq == 0:
        trainer.save_model(os.path.join(script_args.output_dir, f"checkpoint-{round+1}"))
    
    np.save(os.path.join(script_args.output_dir, "training_loss.npy"), np.array(training_loss))

guard.finish(global_dict, fed_args.num_rounds)  # [guard]
save_file({k: v.detach().cpu().contiguous() for k, v in global_dict.items()},  # [guard] for comparison with other runs
          os.path.join(script_args.output_dir, "final_global.safetensors"))
